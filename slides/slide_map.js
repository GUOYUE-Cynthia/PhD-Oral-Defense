#!/usr/bin/env node
// Dev helper: map each <section> to its source line so the browser can deep-link
// back into VS Code (Cmd+click a slide -> jump to its <section> in index.html).
//
//   node slide_map.js          # regenerate slide_lines.js
//   node slide_map.js --watch  # regenerate automatically on every save
//   node slide_map.js --table  # also print the page / hash / line table
//
// slide_lines.js is a generated dev artifact; you can add it to .gitignore.

const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, 'index.html');
const OUT = path.join(__dirname, 'slide_lines.js');

function scan() {
  const lines = fs.readFileSync(SRC, 'utf8').split('\n');
  const rows = [];
  let h = -1, page = 0;
  for (let i = 0; i < lines.length; i++) {
    const m = lines[i].match(/^\s*<section\b([^>]*)>/);
    if (!m) continue;                       // only opening <section ...> tags
    h++;
    const cls = (m[1].match(/class="([^"]*)"/) || [, ''])[1];
    const skip = /title-slide|divider|nonum/.test(cls);
    const disp = skip ? null : ++page;
    // a short human label: first h1/h2, else kicker/part-no
    let label = '';
    for (let j = i; j < Math.min(i + 14, lines.length); j++) {
      const hm = lines[j].match(/<h[12][^>]*>(.*)/);
      if (hm) { label = hm[1]; break; }
      const km = lines[j].match(/class="(?:kicker|part-no)"[^>]*>(.*)/);
      if (km && !label) label = km[1];
    }
    label = label.replace(/<[^>]*>/g, '').replace(/\\\([^)]*\\\)/g, '')
                 .replace(/&amp;/g, '&').replace(/\s+/g, ' ').trim().slice(0, 46);
    rows.push({ h, page: disp, line: i + 1, cls: skip ? cls : '', label });
  }
  return rows;
}

function write(rows) {
  const arr = rows.map(r => r.line);
  const body =
    '// AUTO-GENERATED by slide_map.js — do not edit by hand.\n' +
    '// SLIDE_FILE  = absolute path of index.html (for vscode://file deep links).\n' +
    '// SLIDE_LINES[h] = 1-based source line of the h-th <section> in index.html.\n' +
    'window.SLIDE_FILE = ' + JSON.stringify(SRC) + ';\n' +
    'window.SLIDE_LINES = ' + JSON.stringify(arr) + ';\n';
  const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (prev !== body) { fs.writeFileSync(OUT, body); return true; }
  return false;
}

function table(rows) {
  console.log('page  | hash  | line | section');
  console.log('------+-------+------+---------------------------------');
  for (const r of rows) {
    console.log(
      String(r.page ?? '').padEnd(5) + ' | ' +
      ('#/' + r.h).padEnd(5) + ' | ' +
      String(r.line).padEnd(4) + ' | ' +
      (r.cls ? '[' + r.cls + '] ' : '') + r.label);
  }
}

function run() {
  const rows = scan();
  const changed = write(rows);
  if (process.argv.includes('--table')) table(rows);
  const stamp = new Date().toTimeString().slice(0, 8);
  console.log(`[${stamp}] ${changed ? 'updated' : 'unchanged'} slide_lines.js (${rows.length} sections)`);
}

run();

if (process.argv.includes('--watch')) {
  console.log('watching index.html … (Ctrl-C to stop)');
  // watchFile polls, so it survives editor atomic-saves that fs.watch can miss.
  fs.watchFile(SRC, { interval: 400 }, () => run());
}
